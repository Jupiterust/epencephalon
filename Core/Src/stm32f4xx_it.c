/* DWT timing for the whole CAN1 handler, HAL_CAN_IRQHandler included. The
 * drain budget in docs/CAN协议.md section 0 is 165 us: three FIFO slots x the
 * 55 us shortest acceptable frame. Measuring only onInterrupt() would leave
 * out most of the handler, so the brackets sit in USER CODE regions 0 and 1
 * of each vector. Defined in App/can/can_glue.cpp. */
extern volatile uint32_t g_isrStartCycles;
extern volatile uint32_t g_isrMaxCycles;
extern volatile uint32_t g_isrTotalCycles;
extern volatile uint32_t g_isrCalls;
void app_can1_isr_enter(void);
