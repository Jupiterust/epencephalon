/* Defined in App/can/can_glue.cpp. This file is generated and stays C, so the
 * C++ bus object is reached through one extern "C" forwarder per bus.
 *
 * Called AFTER HAL_CAN_IRQHandler in all four vectors, not just TX: the HAL
 * only invokes its transmit callback on TXOK, so a frame that lost arbitration
 * or went unacknowledged would leave the mailbox refilled by nobody.
 * onInterrupt() is idempotent and is the only refill opportunity on the error
 * path (can_master/README.md:176-188). */
